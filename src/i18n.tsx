const catalogs: Record<Language, TranslationCatalog> = {
  en,
  "pt-BR": ptBR,
};

type I18nContextValue = {
  language: Language;
  t: (key: keyof typeof en, values?: Record<string, string | number>) => string;
};

const I18nContext = createContext<I18nContextValue>({
  language: "en",
  t: (key, values) => translate("en", key, values),
});

function translate(language: Language, key: keyof typeof en, values: Record<string, string | number> = {}) {
  const value = catalogs[language][key] ?? en[key] ?? key;
  return typeof value === "function" ? value(values) : value;
}

export function I18nProvider({ children, language }: { children: ReactNode; language: Language }) {
  return <I18nContext.Provider value={{ language, t: (key, values) => translate(language, key, values) }}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  return useContext(I18nContext);
}
